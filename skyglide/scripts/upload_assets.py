#!/usr/bin/env python3
"""Uploads Sky Glide's icon images to Roblox and writes their ids into the game.

The icons (assets/icons/*.png, Fluent Emoji 3D by Microsoft, MIT licence: assets/CREDITS.md) are
listed in assets/manifest.json. This script uploads each one as a Decal through the Open Cloud
Assets API, waits for the upload operation to finish, stores the asset id in the manifest and
regenerates src/shared/Config/AssetIds.luau, which the UI reads. Icons whose id is still empty
keep showing their emoji fallback in game.

You need an Open Cloud API key with the Assets API (read + write) permission, and the id of the
user or group that will own the images:

  python3 scripts/upload_assets.py --api-key KEY --user-id 1234567
  python3 scripts/upload_assets.py --api-key KEY --group-id 7654321
  ROBLOX_API_KEY=KEY python3 scripts/upload_assets.py --user-id 1234567 --only Wins,Skill
  python3 scripts/upload_assets.py --write-only     # just regenerate AssetIds.luau

Already uploaded icons are skipped (use --force to upload again). Progress is saved after every
icon, so an interrupted run can simply be started again. Only the Python standard library is used.

The game shows a decal through rbxthumb://type=Asset&id=<id>&w=420&h=420, which works for decal
ids without converting them to image ids. Images uploaded by hand (for example with Studio's Asset
Manager bulk import, which gives image ids) go in the manifest's "content" field as
"rbxassetid://<image id>"; run --write-only afterwards. "content" always wins over "assetId".
"""
import argparse
import json
import os
import pathlib
import sys
import time
import urllib.error
import urllib.request
import uuid

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_BASE = "https://apis.roblox.com"


def content_for(entry):
    if entry.get("content"):
        return entry["content"]
    asset_id = entry.get("assetId")
    return f"rbxthumb://type=Asset&id={asset_id}&w=420&h=420" if asset_id else ""


def write_asset_ids(manifest, path):
    lines = [
        "--!strict",
        "-- GENERATED by scripts/upload_assets.py from assets/manifest.json. Don't edit by hand: put ids in",
        "-- the manifest (\"assetId\" from the script, or \"content\" for a hand upload) and run --write-only.",
        "-- Roblox content strings of the uploaded icon images, keyed like Theme.Icons. An empty string",
        "-- means the icon is not uploaded yet, and the UI shows its emoji instead.",
        "export type AssetIds = { Icons: { [string]: string } }",
        "",
        "local AssetIds: AssetIds = {",
        "\tIcons = {",
    ]
    for key in sorted(manifest["icons"]):
        entry = manifest["icons"][key]
        lines.append(f'\t\t{key} = "{content_for(entry)}",')
    lines += ["\t},", "}", "", "return AssetIds", ""]
    path.write_text("\n".join(lines))


def multipart(fields, files):
    """Encodes form fields and (name, filename, content_type, bytes) files as multipart/form-data."""
    boundary = "----skyglide" + uuid.uuid4().hex
    out = bytearray()
    for name, value in fields.items():
        out += f"--{boundary}\r\nContent-Disposition: form-data; name=\"{name}\"\r\n\r\n".encode()
        out += value.encode() + b"\r\n"
    for name, filename, ctype, data in files:
        out += (f"--{boundary}\r\nContent-Disposition: form-data; name=\"{name}\"; filename=\"{filename}\"\r\n"
                f"Content-Type: {ctype}\r\n\r\n").encode()
        out += data + b"\r\n"
    out += f"--{boundary}--\r\n".encode()
    return bytes(out), f"multipart/form-data; boundary={boundary}"


def request(method, url, api_key, body=None, ctype=None, attempts=5):
    """JSON request with retries on rate limits (429) and server errors (5xx)."""
    delay = 2.0
    for attempt in range(attempts):
        req = urllib.request.Request(url, data=body, method=method)
        req.add_header("x-api-key", api_key)
        if ctype:
            req.add_header("Content-Type", ctype)
        try:
            with urllib.request.urlopen(req, timeout=60) as res:
                return json.loads(res.read().decode() or "{}")
        except urllib.error.HTTPError as e:
            detail = e.read().decode(errors="replace")[:400]
            if (e.code == 429 or e.code >= 500) and attempt < attempts - 1:
                wait = float(e.headers.get("Retry-After") or delay)
                print(f"    {e.code}, retrying in {wait:.0f} s")
                time.sleep(wait)
                delay *= 2
                continue
            raise RuntimeError(f"{method} {url} -> HTTP {e.code}: {detail}") from None
    raise RuntimeError(f"{method} {url} failed after {attempts} attempts")


def upload_one(root, base, api_key, creator, key, entry, poll_seconds=1.0, timeout=120):
    path = root / "assets" / entry["file"]
    meta = {
        "assetType": "Decal",
        "displayName": f"SkyGlide {key} icon",
        "description": "Sky Glide UI icon (Fluent Emoji 3D, MIT licence).",
        "creationContext": {"creator": creator},
    }
    body, ctype = multipart({"request": json.dumps(meta)}, [("fileContent", path.name, "image/png", path.read_bytes())])
    op = request("POST", f"{base}/assets/v1/assets", api_key, body, ctype)
    started = time.time()
    while True:
        if op.get("done"):
            if "response" in op and op["response"].get("assetId"):
                return str(op["response"]["assetId"])
            raise RuntimeError(f"upload of {key} failed: {json.dumps(op.get('error') or op.get('status') or op)[:400]}")
        op_path = op.get("path") or ""
        if not op_path.startswith("operations/"):
            raise RuntimeError(f"unexpected reply for {key}: {json.dumps(op)[:400]}")
        if time.time() - started > timeout:
            raise RuntimeError(f"upload of {key} still processing after {timeout} s ({op_path}); run again later")
        time.sleep(poll_seconds)
        poll_seconds = min(poll_seconds * 1.5, 5.0)
        op = request("GET", f"{base}/assets/v1/{op_path}", api_key)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--api-key", default=os.environ.get("ROBLOX_API_KEY", ""))
    owner = parser.add_mutually_exclusive_group()
    owner.add_argument("--user-id")
    owner.add_argument("--group-id")
    parser.add_argument("--only", default="", help="comma-separated icon keys (default: all)")
    parser.add_argument("--force", action="store_true", help="upload again even when an id is stored")
    parser.add_argument("--dry-run", action="store_true", help="list what would be uploaded")
    parser.add_argument("--write-only", action="store_true", help="only regenerate AssetIds.luau")
    parser.add_argument("--base-url", default=DEFAULT_BASE, help=argparse.SUPPRESS)  # tests point this at a mock
    parser.add_argument("--poll", type=float, default=1.0, help=argparse.SUPPRESS)
    parser.add_argument("--root", default=str(ROOT), help=argparse.SUPPRESS)  # tests run on a copy
    args = parser.parse_args(argv)

    root = pathlib.Path(args.root)
    manifest_path = root / "assets" / "manifest.json"
    output = root / "src" / "shared" / "Config" / "AssetIds.luau"
    manifest = json.loads(manifest_path.read_text())
    if args.write_only:
        write_asset_ids(manifest, output)
        print(f"wrote {output.relative_to(root)}")
        return 0
    only = {k.strip() for k in args.only.split(",") if k.strip()}
    unknown = only - set(manifest["icons"])
    if unknown:
        parser.error("unknown icon keys: " + ", ".join(sorted(unknown)))
    def stored(entry):
        return entry.get("assetId") or entry.get("content")
    todo = [k for k in sorted(manifest["icons"]) if (not only or k in only) and (args.force or not stored(manifest["icons"][k]))]
    if args.dry_run:
        for key in todo:
            print(f"would upload {key}: assets/{manifest['icons'][key]['file']}")
        print(f"{len(todo)} to upload")
        return 0
    if not args.api_key:
        parser.error("--api-key (or ROBLOX_API_KEY) is required")
    if not (args.user_id or args.group_id):
        parser.error("--user-id or --group-id is required (the owner of the uploaded images)")
    creator = {"userId": str(args.user_id)} if args.user_id else {"groupId": str(args.group_id)}

    failed = []
    for key in todo:
        entry = manifest["icons"][key]
        print(f"uploading {key} ({entry['file']})")
        try:
            asset_id = upload_one(root, args.base_url.rstrip("/"), args.api_key, creator, key, entry, args.poll)
        except Exception as e:  # keep going; report at the end
            print(f"    FAILED: {e}")
            failed.append(key)
            continue
        entry["assetId"] = asset_id
        manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
        write_asset_ids(manifest, output)
        print(f"    asset id {asset_id}")
    write_asset_ids(manifest, output)
    print(f"done: {len(todo) - len(failed)} uploaded, {len(failed)} failed; wrote {output.relative_to(root)}")
    if failed:
        print("failed: " + ", ".join(failed) + " (run again to retry)")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
